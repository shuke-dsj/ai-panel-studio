export function seedCurated(store:Store){
  if(store.list().some(d=>d.source==='curated'))return;
  const names=['林远','周成','陈芷','王峻','许澄'];const occupations=['产品研究负责人','资深产品经理','解决方案架构师','风险与合规顾问','运营与交付负责人'];const colors=['#15745b','#227a64','#427abf','#8c58ac','#b78626'];
  for(const example of examples){
    const d=store.create(example.topic,4,12,'curated');
    const people:Participant[]=names.map((name,i)=>({id:randomUUID(),discussionId:d.id,role:i?'expert':'moderator',name,occupation:occupations[i],title:i?'圆桌评审专家':'圆桌主持人',stance:i?example.stance[i-1]:'中立 · 澄清问题与收敛结论',focus:i?example.focus[i-1]:'议题澄清、观点对齐与总结',color:colors[i]}));
    store.roster(d.id,people);
    store.message(d.id,{participantId:people[0].id,text:example.opening,replyTo:null,addressedTo:null,phase:'exploration'});
    example.lines.forEach(([speaker,text],index)=>{
      if(index===4)store.message(d.id,{participantId:people[0].id,text:'我们进入交叉讨论。请针对前面出现的条件和反对意见回应：哪些前提可以缩小范围来满足，哪些仍然阻止推进？',replyTo:null,addressedTo:people[1].id,phase:'exchange'});
      const previous=store.messages(d.id).at(-1)!;store.message(d.id,{participantId:people[Number(speaker)].id,text:String(text),replyTo:index?previous.id:null,addressedTo:null,phase:index<4?'exploration':'exchange'});
    });
    const messages=store.messages(d.id);const support=messages.filter(m=>m.text.includes(example.consensus)&&m.participantId!==people[0].id);
    store.replaceInsights(d.id,[{id:'consensus-1',kind:'consensus',text:example.consensusText,messageIds:support.map(m=>m.id),positions:support.map(m=>({participantId:m.participantId,view:example.consensus}))},{id:'disagreement-1',kind:'disagreement',text:example.dispute,messageIds:messages.filter(m=>m.participantId===people[1].id||m.participantId===people[3].id).slice(-2).map(m=>m.id),positions:[{participantId:people[1].id,view:example.stance[0]},{participantId:people[3].id,view:example.stance[2]}]}],example.summary);
    store.update(d.id,{status:'completed',phase:'closing',summary:example.summary},'completed');store.resetActivities(d.id);
  }
}
