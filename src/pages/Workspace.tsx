import { useEffect, useRef, useState } from 'react';
import {
  Menu,
  Pause,
  Play,
  Square,
  RefreshCw,
  Send,
  Mic,
  AlignLeft,
  CircleAlert,
  Users,
  X,
  LoaderCircle,
} from 'lucide-react';
import { api, type Health } from '../lib/api';
import { usePanel } from '../lib/usePanel';
import { statusLabels, phaseLabels, type DirectionMode } from '../../shared/types';
import { RoundTable } from '../components/RoundTable';
import { GuestInspectors } from '../components/GuestInspectors';
import { Transcript } from '../components/Transcript';
import { DiscussionResults } from '../components/DiscussionResults';
export function Workspace({
  id,
  health,
  onMenu,
}: {
  id?: string;
  health: Health | null;
  onMenu: () => void;
}) {
  const panel = usePanel(id),
    s = panel.snapshot,
    d = s?.discussion;
  const [text, setText] = useState(''),
    [count, setCount] = useState(4),
    [maxTurns, setMaxTurns] = useState(48);
  const [mode, setMode] = useState<DirectionMode>('focus'),
    [inspectors, setInspectors] = useState<string[]>([]);
  const [view, setView] = useState<'table' | 'transcript'>('table'),
    [resultsOpen, setResultsOpen] = useState(false);
  const [focusMessage, setFocusMessage] = useState<string | null>(null),
    [localError, setLocalError] = useState(''),
    [sending, setSending] = useState(false),
    [endConfirm, setEndConfirm] = useState(false);
  const roster = !!d && ['draft', 'generating', 'roster_ready'].includes(d.status);
  const readOnly =
    !!d &&
    (d.source === 'curated' || (!!health && (d.source === 'test') !== (health.mode === 'demo')));
  const pending = !!panel.pending || sending;
  const autoGenerated = useRef(false);
  useEffect(() => {
    setInspectors((old) => {
      const valid = old.filter((id) => s?.participants.some((p) => p.id === id));
      return valid.length === old.length ? old : valid;
    });
  }, [s?.participants]);
  useEffect(() => {
    if (d?.status === 'draft' && !d.error && !autoGenerated.current && !readOnly) {
      autoGenerated.current = true;
      void panel.command('roster');
    }
  }, [d?.status, d?.error, readOnly, panel.command]);
  function reference(messageId: string) {
    setFocusMessage(messageId);
    setView('transcript');
    setResultsOpen(false);
  }
  function select(personId: string) {
    setInspectors((old) =>
      old.includes(personId) ? old.filter((i) => i !== personId) : [...old, personId],
    );
  }
  async function submit(e: React.FormEvent) {
    e.preventDefault();
    if (!text.trim() || sending || panel.pending === 'directions') return;
    setSending(true);
    setLocalError('');
    try {
      if (!id || readOnly) {
        const created = await api.create({ topic: text.trim(), expertCount: count, maxTurns });
        window.location.hash = `/discussion/${created.id}`;
      } else {
        const result = await panel.command('directions', {
          text: text.trim(),
          mode,
          clientRequestId: crypto.randomUUID(),
        });
        if (result) setText('');
      }
    } catch (error) {
      setLocalError(error instanceof Error ? error.message : '操作未完成');
    } finally {
      setSending(false);
    }
  }
  async function confirm() {
    const confirmed = await panel.command('confirm');
    if (confirmed) await panel.command('start');
  }
  const latest = s?.messages.at(-1),
    latestPerson = s?.participants.find((p) => p.id === latest?.participantId),
    turns = d ? d.turns - (d.cycleStartTurns ?? 0) : 0;
  return (
    <main className={`workspace-main ${resultsOpen ? 'results-open' : ''}`}>
      <section className="workspace-center">
        <header className="workspace-topbar">
          <button className="icon-button menu-button" aria-label="打开讨论组列表" onClick={onMenu}>
            <Menu size={20} />
          </button>
          <div className="workspace-heading">
            <h1 title={d?.effectiveTopic ?? d?.topic}>
              {d?.effectiveTopic ?? d?.topic ?? '新建圆桌讨论'}
            </h1>
            <p>
              {d ? (
                <>
                  <i className={`status-dot status-${d.status}`} />
                  {statusLabels[d.status]} · {turns}次专家发言 / 上限{d.maxTurns}
                </>
              ) : (
                '输入议题，邀请不同视角一起评审。'
              )}
            </p>
          </div>
          <div className="workspace-actions">
            {d && !readOnly && (
              <>
                {['ready', 'paused', 'error'].includes(d.status) && (
                  <button
                    className="button"
                    disabled={pending}
                    onClick={() => panel.command(d.status === 'ready' ? 'start' : 'resume')}
                  >
                    <Play size={15} />
                    {d.status === 'ready'
                      ? '开始讨论'
                      : d.status === 'error'
                        ? '重试继续'
                        : '继续讨论'}
                  </button>
                )}
                {['running', 'pausing'].includes(d.status) && (
                  <button
                    className="button"
                    disabled={pending || d.status === 'pausing'}
                    onClick={() => panel.command('pause')}
                  >
                    <Pause size={15} />
                    {d.status === 'pausing' ? '正在暂停' : '暂停讨论'}
                  </button>
                )}
                {['running', 'pausing', 'paused', 'error'].includes(d.status) && (
                  <button
                    className="button primary"
                    disabled={pending}
                    onClick={() => setEndConfirm(true)}
                  >
                    <Square size={14} />
                    结束讨论
                  </button>
                )}
              </>
            )}
            <button
              className="icon-button mobile-results"
              aria-label="打开讨论成果"
              onClick={() => setResultsOpen(!resultsOpen)}
            >
              <AlignLeft size={20} />
            </button>
          </div>
        </header>
        {(panel.error || localError || d?.error) && (
          <div className="workspace-error" role="alert">
            <CircleAlert size={17} />
            <span>{localError || panel.error || d?.error}</span>
          </div>
        )}
        {d?.focus && (
          <div className="current-focus">
            <strong>当前焦点</strong>
            <span>{d.focus}</span>
            <small>v{d.directionVersion}</small>
          </div>
        )}
        {d && (
          <div className="workspace-info">
            <span>
              {d.source === 'curated'
                ? '人工编写示例 · 非模型运行'
                : d.source === 'test'
                  ? '确定性演示 · 非真实模型结论'
                  : '真实模型 · 虚构专家'}
            </span>
            <span className={`connection ${panel.connection}`}>
              {panel.connection === 'connected'
                ? '实时连接'
                : panel.connection === 'reconnecting'
                  ? '正在重连'
                  : '连接中'}
            </span>
          </div>
        )}
        <div className="workspace-content">
          {id && !s ? (
            <div className="workspace-loading">
              <LoaderCircle className="spin" size={24} />
              正在载入讨论…
            </div>
          ) : (
            <>
              {!!s && !!inspectors.length && (
                <GuestInspectors
                  snapshot={s}
                  ids={inspectors}
                  onClose={select}
                  onReference={reference}
                />
              )}
              {roster && (
                <div className="roster-banner">
                  <div>
                    <strong>
                      {d?.status === 'generating'
                        ? '正在生成虚构专家阵容…'
                        : s?.participants.length
                          ? '确认阵容后开始讨论'
                          : '话题已创建，先生成阵容'}
                    </strong>
                    <span>
                      {d?.rosterStale
                        ? '前提已更新，请重新生成阵容。'
                        : '点击嘉宾查看职业、Title、立场和关注点。'}
                    </span>
                  </div>
                  <div>
                    <button
                      className="button"
                      disabled={pending || d?.status === 'generating'}
                      onClick={() => panel.command('roster')}
                    >
                      <RefreshCw size={15} />
                      {s?.participants.length ? '重新生成阵容' : '生成嘉宾阵容'}
                    </button>
                    {!!s?.participants.length && (
                      <button
                        className="button primary"
                        disabled={pending || d?.rosterStale || d?.status !== 'roster_ready'}
                        onClick={confirm}
                      >
                        确认并开始讨论
                      </button>
                    )}
                  </div>
                </div>
              )}
              <div className="stage-tabs" aria-label="讨论视图">
                <button
                  className={view === 'table' ? 'active' : ''}
                  onClick={() => setView('table')}
                >
                  <Users size={15} />
                  圆桌现场
                </button>
                <button
                  className={view === 'transcript' ? 'active' : ''}
                  onClick={() => setView('transcript')}
                >
                  <AlignLeft size={15} />
                  现场记录{s ? `（${s.messages.length}）` : ''}
                </button>
              </div>
              {view === 'table' ? (
                <RoundTable
                  snapshot={s}
                  count={d?.expertCount ?? count}
                  selected={inspectors}
                  onSelect={select}
                />
              ) : s ? (
                <Transcript snapshot={s} focusMessage={focusMessage} />
              ) : (
                <div className="no-transcript">讨论开始后，正式发言将保存在这里。</div>
              )}
            </>
          )}
        </div>
        <div className="latest-speech">
          <Mic size={17} />
          <div>
            <strong>
              {latest
                ? `最新${latest.kind === 'direction' ? '用户调整' : '正式发言'} · ${latestPerson?.name ?? '你'}`
                : '等待一场新的观点交锋'}
            </strong>
            <p>{latest?.text ?? '先提出议题与专家人数，再确认主持人和专家阵容。'}</p>
          </div>
          <button
            className="button"
            disabled={!s}
            onClick={() => setView(view === 'table' ? 'transcript' : 'table')}
          >
            <AlignLeft size={15} />
            {view === 'table' ? '现场记录' : '返回圆桌'}
          </button>
        </div>
        <form className="workspace-composer" onSubmit={submit}>
          <textarea
            aria-label={id && !readOnly ? '调整讨论方向' : '讨论话题'}
            placeholder={
              id && !readOnly ? '调整当前讨论的焦点，或明确更新前提…' : '输入一个值得讨论的话题…'
            }
            maxLength={2000}
            rows={2}
            value={text}
            onChange={(e) => setText(e.target.value)}
            required
            onKeyDown={(e) => {
              if ((e.metaKey || e.ctrlKey) && e.key === 'Enter')
                e.currentTarget.form?.requestSubmit();
            }}
          />
          <div className="composer-controls">
            <div className="composer-options">
              {id && !readOnly ? (
                <fieldset className="direction-options">
                  <legend>模式</legend>
                  <label>
                    <input
                      type="radio"
                      name="direction"
                      checked={mode === 'focus'}
                      onChange={() => setMode('focus')}
                    />
                    调整焦点
                  </label>
                  <label>
                    <input
                      type="radio"
                      name="direction"
                      checked={mode === 'replace'}
                      onChange={() => setMode('replace')}
                    />
                    更新前提
                  </label>
                </fieldset>
              ) : (
                <span className="composer-mode">议题</span>
              )}
              <label className="expert-select">
                专家人数
                <select
                  aria-label="专家人数"
                  disabled={!!id && !readOnly}
                  value={id && !readOnly ? (d?.expertCount ?? count) : count}
                  onChange={(e) => setCount(Number(e.target.value))}
                >
                  {[2, 3, 4, 5, 6].map((n) => (
                    <option key={n}>{n}</option>
                  ))}
                </select>
              </label>
              {!id || readOnly ? (
                <label className="boundary-select">
                  自动收敛
                  <select
                    aria-label="发言安全上限"
                    value={maxTurns}
                    onChange={(e) => setMaxTurns(Number(e.target.value))}
                  >
                    <option value={48}>上限48次</option>
                    <option value={96}>上限96次</option>
                  </select>
                </label>
              ) : (
                <span className="boundary-note">自动收敛 · 上限{d?.maxTurns}次</span>
              )}
            </div>
            <button
              className="send-button"
              type="submit"
              aria-label={
                !id || readOnly
                  ? '创建讨论组'
                  : d?.status === 'completed'
                    ? '开始新一轮'
                    : '发送讨论调整'
              }
              disabled={!text.trim() || sending || panel.pending === 'directions'}
            >
              {sending ? <LoaderCircle className="spin" size={20} /> : <Send size={20} />}
            </button>
          </div>
          <p className="composer-hint">
            {id && !readOnly
              ? mode === 'focus'
                ? '保留硬约束，仅调整关注重点。已结束的讨论会开启新一轮。'
                : '明确替换当前前提；旧结论归档，专家将按新前提重新判断。'
              : readOnly
                ? '此记录只读；输入议题可新建讨论组。'
                : '另配1位主持人；达到发言、时间或调用预算时会明确收束。'}
          </p>
        </form>
        <footer className="workspace-footnote">
          AI生成内容，请独立判断{d ? ` · ${phaseLabels[d.phase]}` : ''}
        </footer>
      </section>
      {resultsOpen && (
        <button
          className="results-close icon-button"
          aria-label="关闭讨论成果"
          onClick={() => setResultsOpen(false)}
        >
          <X size={19} />
        </button>
      )}
      <DiscussionResults snapshot={s} onReference={reference} />
      {endConfirm && (
        <div className="workspace-modal-shade">
          <section
            role="dialog"
            aria-modal="true"
            aria-labelledby="end-title"
            className="workspace-dialog"
          >
            <h2 id="end-title">结束本轮讨论？</h2>
            <p>当前发言完成后，主持人会整理已有共识、分歧与下一步。之后仍可输入方向开启新一轮。</p>
            <div>
              <button className="button" onClick={() => setEndConfirm(false)}>
                继续观看
              </button>
              <button
                className="button primary"
                onClick={async () => {
                  setEndConfirm(false);
                  await panel.command('end');
                }}
              >
                确认结束
              </button>
            </div>
          </section>
        </div>
      )}
    </main>
  );
}
